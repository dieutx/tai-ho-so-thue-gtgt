"""Qt Widgets layout translated from the supplied v2 design references."""

from PySide6.QtCore import QDate, Qt
from PySide6.QtGui import QAction, QKeySequence
from PySide6.QtWidgets import (
    QComboBox,
    QDateEdit,
    QFrame,
    QHBoxLayout,
    QHeaderView,
    QLabel,
    QMenu,
    QProgressBar,
    QPushButton,
    QSizePolicy,
    QStackedLayout,
    QStyle,
    QTabBar,
    QTableView,
    QTextBrowser,
    QVBoxLayout,
    QWidget,
)

from . import __version__
from .settings_store import default_output
from .table_model import COLUMNS, RecordsModel, RecordsProxy, SelectionHeader


def build_workspace(window):
    from .ui import TITLES, PathEdit, button, field
    self = window
    root = QWidget()
    root.setMinimumSize(0, 0)
    self.setCentralWidget(root)
    self.layout_root = QVBoxLayout(root)
    self.layout_root.setContentsMargins(12, 8, 12, 8)
    self.layout_root.setSpacing(7)
    header = QHBoxLayout()
    self.title = QLabel('Tải Hồ Sơ Thuế')
    self.title.setObjectName('title')
    self.title.setToolTip('Phần mềm bên thứ ba, không phải ứng dụng chính thức của cơ quan thuế')
    header.addWidget(self.title)
    self.version_button = button('v' + __version__, self.show_release, 'Phiên bản và cập nhật')
    header.addWidget(self.version_button)
    header.addStretch()
    self.account_label = QLabel('MST: —')
    self.account_label.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
    self.account_label.setContextMenuPolicy(Qt.ContextMenuPolicy.CustomContextMenu)
    self.account_label.customContextMenuRequested.connect(self.account_context_menu)
    header.addWidget(self.account_label)
    self.source_badge = QLabel('Chưa đăng nhập')
    header.addWidget(self.source_badge)
    self.account_button = button('Đăng nhập', self.open_login)
    self.account_button.setObjectName('account')
    header.addWidget(self.account_button)
    self.logout_button = button('', self.logout, 'Đăng xuất và xóa phiên đăng nhập')
    self.logout_button.setIcon(self.style().standardIcon(QStyle.StandardPixmap.SP_DialogCloseButton))
    header.addWidget(self.logout_button)
    self.settings_button = button('', self.settings, 'Cài đặt')
    self.settings_button.setIcon(self.style().standardIcon(QStyle.StandardPixmap.SP_FileDialogDetailedView))
    header.addWidget(self.settings_button)
    self.layout_root.addLayout(header)
    self.tabs = QTabBar()
    self.tabs.setExpanding(False)
    for title in TITLES:
        self.tabs.addTab(title)
    self.tabs.currentChanged.connect(self.mode_changed)
    self.navigation = QComboBox()
    self.navigation.addItems(TITLES)
    self.navigation.currentIndexChanged.connect(self.tabs.setCurrentIndex)
    self.navigation.setAccessibleName('Chọn nghiệp vụ')
    self.layout_root.addWidget(self.tabs)
    self.layout_root.addWidget(self.navigation)
    self.navigation.hide()
    self.warning = QLabel()
    self.warning.setObjectName('warning')
    self.warning.setWordWrap(True)
    self.layout_root.addWidget(self.warning)
    self.condition_summary = QWidget()
    summary = QHBoxLayout(self.condition_summary)
    summary.setContentsMargins(8, 4, 8, 4)
    self.summary_text = QLabel()
    self.summary_text.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Preferred)
    summary.addWidget(self.summary_text, 1)
    self.edit_conditions = button('Sửa điều kiện', lambda: self.collapse_conditions(False))
    summary.addWidget(self.edit_conditions)
    self.layout_root.addWidget(self.condition_summary)
    self.condition_summary.hide()
    self.config_panel = QWidget()
    self.config_layout = QHBoxLayout(self.config_panel)
    self.config_layout.setContentsMargins(0, 0, 0, 0)
    self.config_layout.setSpacing(6)
    self.online_panel = QWidget()
    dates = QHBoxLayout(self.online_panel)
    dates.setContentsMargins(0, 0, 0, 0)
    dates.setSpacing(5)
    self.date_type = QLabel('Ngày nộp')
    dates.addWidget(self.date_type)
    self.preset = QComboBox()
    for label, value in [('Tháng này', 'month'), ('Tháng trước', 'previous'), ('Quý này', 'quarter'),
                         ('Năm nay', 'year'), ('12 tháng qua', 'twelve'), ('Tùy chỉnh', 'custom')]:
        self.preset.addItem(label, value)
    self.preset.setAccessibleName('Chọn nhanh kỳ tra cứu')
    dates.addWidget(self.preset)
    self.from_date, self.to_date = QDateEdit(), QDateEdit()
    previous = QDate.currentDate().addMonths(-1)
    first = QDate(previous.year(), previous.month(), 1)
    for label, widget, day in [('Từ', self.from_date, first), ('Đến', self.to_date, first.addMonths(1).addDays(-1))]:
        dates.addWidget(QLabel(label))
        widget.setCalendarPopup(True)
        widget.setDisplayFormat('dd/MM/yyyy')
        widget.setDate(day)
        widget.setMinimumWidth(102)
        widget.setMaximumWidth(122)
        widget.setAccessibleName(label + ' ngày')
        widget.dateChanged.connect(self.dates_changed)
        dates.addWidget(widget)
    self.preset.setCurrentIndex(1)
    self.preset.currentIndexChanged.connect(self.apply_preset)
    self.config_layout.addWidget(self.online_panel)
    self.offline_panel = QWidget()
    source = QHBoxLayout(self.offline_panel)
    source.setContentsMargins(0, 0, 0, 0)
    source.addWidget(QLabel('Nguồn'))
    self.input_path = PathEdit('Thư mục nguồn ZIP/XML')
    source.addWidget(self.input_path, 1)
    self.source_info = QLabel()
    source.addWidget(self.source_info)
    choose = QPushButton('Chọn nguồn')
    choose_menu = QMenu(choose)
    choose_menu.addAction('Chọn thư mục ZIP/XML…', lambda: self.browse(self.input_path))
    choose_menu.addAction('Chọn tệp XML/ZIP…', self.choose_xml_files)
    choose.setMenu(choose_menu)
    choose.setAccessibleName('Chọn tệp hoặc thư mục XML/ZIP cục bộ')
    source.addWidget(choose)
    self.stage = QComboBox()
    for label, value in [('Toàn bộ', 'all'), ('Kiểm kê', 'inventory'), ('Đọc XML', 'parse'),
                         ('Phân loại', 'classify'), ('Xuất Excel', 'export')]:
        self.stage.addItem(label, value)
    source.addWidget(self.stage)
    self.config_layout.addWidget(self.offline_panel)
    self.offline_panel.hide()
    self.filters, self.csv, self.forms_dir, self.rehash = {}, False, '', False
    self.output_panel = QWidget()
    output = QHBoxLayout(self.output_panel)
    output.setContentsMargins(0, 0, 0, 0)
    output.setSpacing(5)
    self.output_label = QLabel('Nơi lưu hồ sơ')
    output.addWidget(self.output_label)
    self.output = PathEdit('Thư mục lưu hồ sơ')
    self.output.setText(self.preferences.output or str(default_output()))
    output.addWidget(self.output, 1)
    output.addWidget(button('Thay đổi', lambda: self.browse(self.output), 'Thay đổi thư mục lưu hồ sơ'))
    self.open_folder_button = button('Mở thư mục', self.open_output)
    output.addWidget(self.open_folder_button)
    self.options_button = button('Tùy chọn', self.task_options, 'Bộ lọc và tùy chọn nghiệp vụ')
    output.addWidget(self.options_button)
    self.query = button('Tra cứu', lambda: self.start(True), 'Chỉ tra cứu, không ghi catalog hoặc tải tệp')
    self.query.setObjectName('query')
    self.start_button = button('Tra cứu và tải', lambda: self.start(False), 'Tra cứu và tải; giữ tệp hợp lệ đã có')
    self.start_button.setObjectName('primary')
    output.addWidget(self.query)
    output.addWidget(self.start_button)
    self.config_layout.addWidget(self.output_panel, 1)
    self.layout_root.addWidget(self.config_panel)
    self.xml_notice = QLabel('Đọc XML cục bộ • Không gửi tệp ra ngoài • Kết quả parse không xác thực chữ ký số')
    self.xml_notice.setWordWrap(True)
    self.xml_notice.setObjectName('hint')
    self.layout_root.addWidget(self.xml_notice)
    self.xml_notice.hide()
    self.results_panel = QWidget()
    results = QVBoxLayout(self.results_panel)
    results.setContentsMargins(0, 0, 0, 0)
    results.setSpacing(5)
    self.counts = QLabel('Tìm thấy 0    Đã tải 0    Chưa tải 0    Tải lỗi 0')
    self.counts.setObjectName('counters')
    self.counts.setToolTip('Toàn bộ kết quả của tài khoản, tab và kỳ đã tra cứu; không đổi theo bộ lọc bảng')
    results.addWidget(self.counts)
    filter_row = QHBoxLayout()
    self.search = field('Tìm tên, mã hồ sơ, số chứng từ hoặc kỳ…')
    self.search.setClearButtonEnabled(True)
    filter_row.addWidget(self.search, 1)
    self.file_filter = QComboBox()
    for label, value in [('Tất cả hồ sơ', 'all'), ('Chưa tải', 'not_downloaded'), ('Đã tải', 'downloaded'),
                         ('Tải lỗi', 'failed'), ('Cần kiểm tra', 'review')]:
        self.file_filter.addItem(label, value)
    filter_row.addWidget(self.file_filter)
    self.missing_button = button('Tải chưa tải', self.download_missing, 'Chỉ tải hồ sơ chưa có tệp trong toàn bộ kết quả của kỳ này')
    self.retry_button = button('Thử lại tệp lỗi', self.retry_failed)
    self.verify_button = button('Kiểm tra tệp', self.verify_files, 'Kiểm tra lại tệp đã xóa, di chuyển hoặc hỏng; không gọi mạng')
    filter_row.addWidget(self.missing_button)
    filter_row.addWidget(self.retry_button)
    filter_row.addWidget(self.verify_button)
    results.addLayout(filter_row)
    self.selection_bar = QWidget()
    selection = QHBoxLayout(self.selection_bar)
    selection.setContentsMargins(0, 0, 0, 0)
    self.selection_label = QLabel()
    selection.addWidget(self.selection_label)
    selection.addWidget(button('Tải các tệp đã chọn', self.download_checked))
    selection.addWidget(button('Bỏ chọn', self.clear_selection))
    selection.addStretch()
    results.addWidget(self.selection_bar)
    self.selection_bar.hide()
    self.model = RecordsModel(self)
    self.proxy_model = RecordsProxy(self)
    self.proxy_model.setSourceModel(self.model)
    self.search.textChanged.connect(self.proxy_model.setFilterFixedString)
    self.search.textChanged.connect(self.update_empty)
    self.file_filter.currentIndexChanged.connect(lambda: self.set_file_filter())
    self.model.selection_changed.connect(self.selection_changed)
    self.table = QTableView()
    self.table.setMinimumSize(0, 36)
    self.table.setModel(self.proxy_model)
    self.table.setHorizontalHeader(SelectionHeader(Qt.Orientation.Horizontal, self.table))
    self.table.horizontalHeader().setAccessibleName('Chọn tất cả hồ sơ đang hiển thị')
    self.model.selection_changed.connect(self.table.horizontalHeader().viewport().update)
    self.table.setAlternatingRowColors(False)
    self.table.setSelectionBehavior(QTableView.SelectionBehavior.SelectRows)
    self.table.setEditTriggers(QTableView.EditTrigger.NoEditTriggers)
    self.table.setSortingEnabled(True)
    self.table.horizontalHeader().setSectionResizeMode(QHeaderView.ResizeMode.Interactive)
    self.table.horizontalHeader().setStretchLastSection(False)
    self.table.horizontalHeader().setMinimumSectionSize(32)
    self.table.horizontalHeader().sectionClicked.connect(self.select_visible_header)
    self.table.verticalHeader().hide()
    self.table.verticalHeader().setDefaultSectionSize(43)
    self.table.clicked.connect(self.table_clicked)
    self.table.activated.connect(lambda _index: self.details())
    self.table.setContextMenuPolicy(Qt.ContextMenuPolicy.CustomContextMenu)
    self.table.customContextMenuRequested.connect(self.context_menu)
    self.table.sortByColumn(next(i for i, (key, _) in enumerate(COLUMNS['tax']) if key == 'ngay_nop'), Qt.SortOrder.DescendingOrder)
    table_area = QWidget()
    stacked = QStackedLayout(table_area)
    stacked.setContentsMargins(0, 0, 0, 0)
    stacked.setStackingMode(QStackedLayout.StackingMode.StackAll)
    stacked.addWidget(self.table)
    self.empty = QLabel('Chọn kỳ rồi nhấn Tra cứu')
    self.empty.setAlignment(Qt.AlignmentFlag.AlignCenter)
    self.empty.setWordWrap(True)
    self.empty.setTextFormat(Qt.TextFormat.PlainText)
    self.empty.setAttribute(Qt.WidgetAttribute.WA_TransparentForMouseEvents)
    self.empty.setObjectName('empty')
    stacked.addWidget(self.empty)
    stacked.setCurrentWidget(self.empty)
    self.model.modelReset.connect(self.update_empty)
    self.proxy_model.modelReset.connect(self.update_empty)
    self.proxy_model.rowsInserted.connect(lambda *_args: self.update_empty())
    self.proxy_model.rowsRemoved.connect(lambda *_args: self.update_empty())
    results.addWidget(table_area, 1)
    self.layout_root.addWidget(self.results_panel, 1)
    self.files = QComboBox(self)
    self.files.hide()
    self.files.activated.connect(self.open_file_choice)
    footer = QHBoxLayout()
    self.stop_button = button('Dừng', self.controller.stop, 'Dừng hàng đợi an toàn, giữ tệp đã hoàn tất')
    self.stop_button.setObjectName('stop')
    self.stop_button.setEnabled(False)
    footer.addWidget(self.stop_button)
    self.status = QLabel('Sẵn sàng')
    self.status.linkActivated.connect(lambda _url: self.show_issues())
    self.status.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Preferred)
    footer.addWidget(self.status, 1)
    self.progress = QProgressBar()
    self.progress.setRange(0, 1)
    self.progress.setValue(0)
    self.progress.setTextVisible(False)
    self.progress.setMaximumWidth(80)
    self.progress.setMaximumHeight(6)
    footer.addWidget(self.progress)
    self.history_button = button('Lịch sử tải', self.show_history)
    footer.addWidget(self.history_button)
    self.file_menu = QMenu(self)
    self.folder_button = self.file_menu.addAction('Mở thư mục', self.open_output)
    self.report_button = self.file_menu.addAction('Mở báo cáo', self.open_report)
    self.export_action = self.file_menu.addAction('Xuất danh sách Excel…', self.export_report)
    self.report_button.setEnabled(False)
    self.log_button = self.file_menu.addAction('Nhật ký kỹ thuật (0)', self.show_logs)
    self.file_menu.addAction('Kiểm tra lại tệp trên máy', self.verify_files)
    self.file_menu.addSeparator()
    self.batch_action = self.file_menu.addAction('Tải các nhóm liên tiếp…', self.batch_dialog)
    self.file_menu.addAction('Đọc / sao chép dữ liệu cũ…', self.import_legacy)
    self.outputs_menu = self.file_menu.addMenu('Tệp đã tạo')
    self.menu_button = QPushButton('Công cụ nâng cao')
    self.menu_button.setObjectName('files')
    self.menu_button.setMenu(self.file_menu)
    footer.addWidget(self.menu_button)
    self.layout_root.addLayout(footer)
    self.drawer = QFrame(root)
    self.drawer.setObjectName('drawer')
    drawer = QVBoxLayout(self.drawer)
    heading = QHBoxLayout()
    heading.addWidget(QLabel('Chi tiết hồ sơ'), 1)
    close = button('', self.close_drawer, 'Đóng chi tiết (Esc)')
    close.setIcon(self.style().standardIcon(QStyle.StandardPixmap.SP_DialogCloseButton))
    heading.addWidget(close)
    drawer.addLayout(heading)
    self.detail_text = QTextBrowser()
    self.detail_text.setOpenExternalLinks(False)
    drawer.addWidget(self.detail_text, 1)
    tools = QHBoxLayout()
    tools.addWidget(button('Sao chép mã', self.copy_document_id))
    tools.addWidget(button('Metadata gốc', self.raw_details))
    drawer.addLayout(tools)
    actions = QHBoxLayout()
    self.detail_open = button('Mở tệp', self.open_detail_file)
    self.detail_download = button('Tải tệp', self.download_detail)
    self.detail_download.setObjectName('primary')
    actions.addWidget(self.detail_open)
    actions.addWidget(self.detail_download)
    drawer.addLayout(actions)
    self.drawer.hide()
    self.detail_row = None
    self.subview = QComboBox(self)
    self.subview.hide()
    for key, callback in [('Ctrl+O', self.open_output), ('Ctrl+L', self.show_logs),
                          ('Ctrl+Return', lambda: self.start(False)), ('Ctrl+F', self.search.setFocus),
                          ('Escape', self.close_drawer)]:
        action = QAction(self)
        action.setShortcut(QKeySequence(key))
        action.triggered.connect(callback)
        self.addAction(action)
    for key, callback in [('Ctrl+A', lambda: self.select_visible_header(0)), ('Space', self.toggle_current_checkbox)]:
        action = QAction(self.table)
        action.setShortcut(QKeySequence(key))
        action.setShortcutContext(Qt.ShortcutContext.WidgetWithChildrenShortcut)
        action.triggered.connect(callback)
        self.table.addAction(action)
    self.setAcceptDrops(True)
    self.refresh_account()
    self.sync_actions()
